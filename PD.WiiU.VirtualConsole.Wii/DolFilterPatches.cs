    private static readonly byte[] DitheringBranch = { 0x48, 0x00, 0x00, 0x28 };
    private static readonly byte[] VerticalFilter = { 0x08, 0x08, 0x0A, 0x0C, 0x0A, 0x08, 0x08 };
    private static readonly byte[] VerticalFilterHalved = { 0x04, 0x04, 0x10, 0x10, 0x10, 0x04, 0x04 };

    /// <summary>
    /// Copy of the deflicker setup pattern.
    /// </summary>
    public static byte[] DeflickerPattern => (byte[])Deflicker.Clone();
    /// <summary>
    /// Copy of the dithering setup pattern.
    /// </summary>
    public static byte[] DitheringPattern => (byte[])Dithering.Clone();
    /// <summary>
    /// Copy of the stock vertical filter.
    /// </summary>
    public static byte[] VerticalFilterPattern => (byte[])VerticalFilter.Clone();

    /// <summary>
    /// Turns the final conditional branch of the deflicker setup into an unconditional one, first match only.
    /// </summary>
    /// <param name="dol">main.dol, patched in place.</param>
    /// <returns>True when the pattern was found.</returns>
    public static bool RemoveDeflicker(byte[] dol)
    {
        if (dol is null)
            throw new ArgumentNullException(nameof(dol));

        var at = IndexOf(dol, Deflicker, 0);
        if (at < 0)
            return false;
        DeflickerBranch.CopyTo(dol, at + Deflicker.Length - DeflickerBranch.Length);
        return true;
    }

    /// <summary>
    /// Branches over the dithering setup by rewriting the instruction before it, first match only.
    /// </summary>
    /// <param name="dol">main.dol, patched in place.</param>
    /// <returns>True when the pattern was found.</returns>
    public static bool RemoveDithering(byte[] dol)
    {
        if (dol is null)
            throw new ArgumentNullException(nameof(dol));

        var at = IndexOf(dol, Dithering, DitheringBranch.Length);
        if (at < 0)
            return false;
        DitheringBranch.CopyTo(dol, at - DitheringBranch.Length);
        return true;
    }

    /// <summary>
    /// Replaces every default 8-8-10-12-10-8-8 vertical filter with 4-4-16-16-16-4-4.
    /// </summary>
    /// <param name="dol">main.dol, patched in place.</param>
    /// <returns>Filters rewritten.</returns>
    public static int HalveVerticalFilter(byte[] dol)
    {
        if (dol is null)
            throw new ArgumentNullException(nameof(dol));

        var count = 0;
        var at = IndexOf(dol, VerticalFilter, 0);
        while (at >= 0)
        {
            VerticalFilterHalved.CopyTo(dol, at);
            count++;
            at = IndexOf(dol, VerticalFilter, at + VerticalFilter.Length);
        }
        return count;
    }

    private static int IndexOf(byte[] data, byte[] pattern, int start)
    {
        for (var i = start; i + pattern.Length <= data.Length; i++)
        {
            var j = 0;
            while (j < pattern.Length && data[i + j] == pattern[j])
                j++;
            if (j == pattern.Length)
                return i;
        }
        return -1;
    }
